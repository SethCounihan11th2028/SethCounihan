x_input = float(input("What is the X value?\n "))
y_input = float(input("What is the Y value?\n "))

def add(x, y):
    print(str(x + y))

def subtract(x, y):
    print(str(x - y))

def multiply(x, y):
    print(str(x * y))

def divide(x, y):
    print(str(x / y))

add(x_input, y_input)
subtract(x_input, y_input)
multiply(x_input, y_input)
divide(x_input, y_input)